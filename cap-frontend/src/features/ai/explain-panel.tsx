import { Loader2, Sparkles } from 'lucide-react'
import type { MatchExplanation } from '../../shared/api/api-types'
import { useAiStatus } from './use-ai-status'
import { useExplanation } from './use-explanation'

interface ExplainPanelProps {
  jobId: string
  personIndex: number
  caseKey: string
}

function ExplanationBody({ explanation }: { explanation: MatchExplanation }) {
  return (
    <div className="mt-3 space-y-2 text-xs text-slate-700">
      <p>{explanation.summary}</p>
      {explanation.supports.length > 0 && (
        <p>
          <span className="font-semibold text-emerald-700">Supports: </span>
          {explanation.supports.join('; ')}
        </p>
      )}
      {explanation.weakens.length > 0 && (
        <p>
          <span className="font-semibold text-amber-700">Weakens: </span>
          {explanation.weakens.join('; ')}
        </p>
      )}
      <p>
        <span className="font-semibold">Next step: </span>
        {explanation.next_step}
      </p>
      <p className="text-[11px] text-slate-400">
        AI-generated by {explanation.model}. The match label “{explanation.label}” comes from fixed rules and was not changed.
      </p>
    </div>
  )
}

export function ExplainPanel({ jobId, personIndex, caseKey }: ExplainPanelProps) {
  const status = useAiStatus()
  const { state, explain } = useExplanation(jobId, personIndex, caseKey)
  if (status === null) return null
  if (!status.available) {
    return <p className="text-[11px] text-slate-400">AI explanations are off ({status.reason}).</p>
  }

  return (
    <div className="rounded-xl bg-indigo-50/60 p-4 ring-1 ring-indigo-100">
      <button
        type="button"
        onClick={explain}
        disabled={state.status === 'loading'}
        className="inline-flex items-center gap-1.5 rounded-lg bg-white px-2.5 py-1.5 text-xs font-medium text-indigo-700 shadow-sm ring-1 ring-indigo-200 hover:bg-indigo-50 disabled:opacity-50"
      >
        {state.status === 'loading' ? <Loader2 size={13} className="animate-spin" /> : <Sparkles size={13} />}
        Explain this match with AI
      </button>
      {state.status === 'ready' && <ExplanationBody explanation={state.explanation} />}
      {state.status === 'error' && (
        <p role="alert" className="mt-2 text-xs text-rose-600">{state.message}</p>
      )}
    </div>
  )
}
